"""
ARCH fixture ingestion.

Input: a Django JSON fixture in the shape produced by ``vEnhance/otis-web``
(``fixtures/all.json`` -- a list of ``{"model": ..., "pk": ..., "fields": {...}}``
objects, or an object with an ``objects`` key).

What it extracts
----------------
======================  ==================================================
ARCH model              Target rows in this platform
======================  ==================================================
``arch.problem``        ``Problem`` (``puid`` / ``legacy_puid`` / statement)
``arch.hint``           ``Hint`` (ordered by ``number``)
``arch.solution``       ``Solution`` (``official_tex`` = ground truth)
(any ``*solution*``)    ``Solution`` -- the real repo's model name has
                        changed over time, so the parser sniffs model names
                        and field names instead of hard-coding one
======================  ==================================================

Real-world caveat (measured, not assumed)
-----------------------------------------
The *public* ``fixtures/all.json`` that ships with otis-web is generated by
``fixtures/gen-dummy-data.sh``: it contains faker statements/PUIDs and **no
official solutions at all**.  The parser therefore reports exactly what it found
(``solutions_found: 0``) instead of inventing ground truth.  Production data
comes from the same fixture format with real content; use ``--puid-map`` to
attach human-readable PUIDs (``IMO 2016/4``) to ARCH's 6-character codes.

Nothing in this module touches the Django ORM at import time, so
``scripts/parse_arch_fixture.py`` can use it as a plain command-line tool.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Iterator, Sequence

# --------------------------------------------------------------------------- #
# schema sniffing tables
# --------------------------------------------------------------------------- #
PROBLEM_MODELS = {"arch.problem"}
HINT_MODELS = {"arch.hint"}
SOLUTION_MODEL_HINTS = ("solution", "answer", "solutiontext")

PUID_KEYS = ("puid", "code", "slug", "name", "identifier")
STATEMENT_KEYS = ("statement_tex", "statement", "problem", "content", "text", "description")
HYPERLINK_KEYS = ("hyperlink", "url", "link", "aops_url")
HINT_ORDER_KEYS = ("number", "order_index", "order", "index", "position", "seq")
HINT_TEXT_KEYS = ("content", "content_md", "text", "hint", "body", "message")
SOLUTION_TEXT_KEYS = (
    "official_tex",
    "official_solution",
    "solution_tex",
    "solution",
    "content",
    "answer",
    "text",
    "body",
)
FK_KEYS = ("problem", "problem_id", "problem_pk")

CATEGORY_KEYWORDS = {
    # shortlist codes and words commonly attached to ARCH hints
    "algebra": ("algebra", "alg", "a1", "a2", "a3", "a4", "a5", "a6", "a7", "inequalit", "polynomial"),
    "combinatorics": ("combi", "comb", "c1", "c2", "c3", "c4", "c5", "c6", "c7", "graph", "pigeonhole"),
    "geometry": ("geometry", "geo", "g1", "g2", "g3", "g4", "g5", "g6", "circle", "triangle"),
    "number_theory": ("number theory", "nt", "n1", "n2", "n3", "n4", "n5", "n6", "modular", "prime"),
}

HARD_COMPETITIONS = ("usamo", "tst", "putnam", "imo shortlist", "isl", "rmo", "china tst")

_ARCH_CODE_RE = re.compile(r"^[A-Z0-9]{3,12}$")
_HUMAN_PUID_RE = re.compile(r"\s|/|:")
_IMO_STYLE_RE = re.compile(r"\b(?P<comp>[A-Za-z][A-Za-z .\-]*?)\s+(?P<year>(?:19|20)\d{2})\s*[/#]\s*(?P<num>\d{1,2})\b")


# --------------------------------------------------------------------------- #
# data structures
# --------------------------------------------------------------------------- #
@dataclass
class ParsedHint:
    order_index: int
    content_md: str
    keywords: str = ""
    source_pk: Any = None


@dataclass
class ParsedProblem:
    puid: str
    legacy_puid: str = ""
    statement_tex: str = ""
    hyperlink: str = ""
    category: str = "misc"
    difficulty_track: str = "olympiad"
    hints: list[ParsedHint] = field(default_factory=list)
    official_tex: str = ""
    attribution: str = ""
    source_pk: Any = None
    warnings: list[str] = field(default_factory=list)

    @property
    def puid_quality(self) -> str:
        if self.legacy_puid and self.puid != self.legacy_puid:
            return "mapped"
        if _HUMAN_PUID_RE.search(self.puid) or _IMO_STYLE_RE.search(self.puid):
            return "human"
        if _ARCH_CODE_RE.match(self.puid):
            return "arch-code"
        return "human"


@dataclass
class IngestionResult:
    problems: list[ParsedProblem]
    stats: dict[str, int]
    warnings: list[str] = field(default_factory=list)

    @property
    def n_problems(self) -> int:
        return len(self.problems)

    @property
    def n_hints(self) -> int:
        return sum(len(p.hints) for p in self.problems)

    @property
    def n_solutions(self) -> int:
        return sum(1 for p in self.problems if p.official_tex.strip())

    def report(self) -> dict:
        return {
            "stats": dict(self.stats),
            "problems": len(self.problems),
            "hints": self.n_hints,
            "solutions": self.n_solutions,
            "puid_quality": _tally(p.puid_quality for p in self.problems),
            "categories": _tally(p.category for p in self.problems),
            "tracks": _tally(p.difficulty_track for p in self.problems),
            "warnings": self.warnings[:200],
        }


def _tally(values: Iterable[str]) -> dict[str, int]:
    out: dict[str, int] = {}
    for value in values:
        out[value] = out.get(value, 0) + 1
    return dict(sorted(out.items(), key=lambda kv: -kv[1]))


# --------------------------------------------------------------------------- #
# loading / normalising the fixture
# --------------------------------------------------------------------------- #
def load_fixture(path: str | Path) -> list[dict]:
    """Read a Django JSON fixture (either a list, or ``{"objects": [...]}``)."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(raw, dict):
        for key in ("objects", "data", "fixtures", "rows"):
            if isinstance(raw.get(key), list):
                return raw[key]
        raise ValueError(f"{path}: unsupported fixture shape (keys: {sorted(raw)[:8]})")
    if isinstance(raw, list):
        return raw
    raise ValueError(f"{path}: expected a list of fixture objects")


def _model_key(row: dict) -> str:
    return str(row.get("model", "")).lower()


def _fields(row: dict) -> dict:
    fields = row.get("fields")
    return fields if isinstance(fields, dict) else {}


def _first_str(fields: dict, keys: Sequence[str]) -> str:
    for key in keys:
        value = fields.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return str(value)
    return ""


def _longest_str(fields: dict, *, ignore: Sequence[str] = ()) -> str:
    best = ""
    for key, value in fields.items():
        if key in ignore or not isinstance(value, str):
            continue
        if len(value.strip()) > len(best):
            best = value.strip()
    return best


def _fk_target(fields: dict) -> Any:
    """Problem FK as int pk (or [pk] in some export dialects)."""
    for key in FK_KEYS:
        if key in fields:
            value = fields[key]
            if isinstance(value, list) and value:
                return value[0]
            return value
    return None


def _is_solution_model(model: str) -> bool:
    if model in HINT_MODELS or model in PROBLEM_MODELS:
        return False
    return any(token in model for token in SOLUTION_MODEL_HINTS)


# --------------------------------------------------------------------------- #
# heuristics
# --------------------------------------------------------------------------- #
def _keyword_hits(keyword: str, text: str) -> bool:
    """
    Match a topic keyword at a word boundary.

    Short codes (``nt``, ``a1``, ``g3``) must not match inside ordinary words
    (``nt`` inside "statement", ``g1`` inside "g13"), so they require strict
    boundaries; longer words are matched as prefixes so that "triangle" still
    matches "triangles".
    """
    keyword = keyword.lower()
    if len(keyword) <= 3:
        pattern = rf"(?<![a-z0-9]){re.escape(keyword)}(?![a-z0-9])"
    else:
        pattern = rf"(?<![a-z0-9]){re.escape(keyword)}"
    return re.search(pattern, text) is not None


def infer_category(puid: str, statement: str, hint_keywords: str) -> str:
    """Best-effort subject classification from PUID / hint keywords / statement."""
    labels = f"{hint_keywords} {puid}".lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        if any(_keyword_hits(keyword, labels) for keyword in keywords):
            return category
    body = statement.lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        if any(_keyword_hits(keyword, body) for keyword in keywords):
            return category
    return "misc"


def infer_track(puid: str, statement: str) -> str:
    """Rough difficulty ladder from the problem number / competition name."""
    match = _IMO_STYLE_RE.search(puid) or _IMO_STYLE_RE.search(statement[:400])
    if match:
        number = int(match.group("num"))
        return "hard" if number in {3, 6, 8} else "olympiad"
    lowered = puid.lower()
    if any(name in lowered for name in HARD_COMPETITIONS):
        return "hard"
    if "shortlist" in lowered or "isl" in lowered:
        return "olympiad"
    return "olympiad"


def resolve_puid(raw_puid: str, hyperlink: str, puid_map: dict[str, str]) -> tuple[str, str, str]:
    """
    Return ``(puid, legacy_puid, note)``.

    ``puid_map`` lets an operator attach real olympiad PUIDs to ARCH's opaque
    six-character codes, e.g. ``{"XKPFMI": "IMO 2016/4"}``.
    """
    raw_puid = (raw_puid or "").strip()
    if raw_puid in puid_map:
        return puid_map[raw_puid], raw_puid, ""
    if raw_puid and (_HUMAN_PUID_RE.search(raw_puid) or not _ARCH_CODE_RE.match(raw_puid)):
        return raw_puid, "", ""
    if raw_puid:
        # A bare ARCH code: ingest it (flagged), but prefer a PUID we can derive
        # from the hyperlink when the fixture carries one.
        derived = _puid_from_hyperlink(hyperlink)
        if derived:
            return derived, raw_puid, ""
        return raw_puid, raw_puid, (
            f"puid {raw_puid!r} is an opaque ARCH code - pass --puid-map to attach "
            "a human-readable PUID such as 'IMO 2016/4'"
        )
    # no puid field at all: fall back to the hyperlink, then give up
    derived = _puid_from_hyperlink(hyperlink)
    if derived:
        return derived, "", ""
    return "", "", "row has no PUID at all"


def _puid_from_hyperlink(url: str) -> str:
    """
    Derive a readable PUID from an AoPS/contest URL when possible.

    Examples
    --------
    ``https://artofproblemsolving.com/community/c6h1234567``  -> ``"AoPS c6h1234567"``
    ``https://.../USAMO_2018_Problem_3``                      -> ``"USAMO 2018/3"``
    """
    if not url:
        return ""
    tail = url.rstrip("/").split("/")[-1]
    guess = re.sub(r"[_\-]+", " ", tail)
    match = _IMO_STYLE_RE.search(guess) or re.search(
        r"(?P<comp>[A-Za-z][A-Za-z .\-]*?)\s+(?P<year>(?:19|20)\d{2})\s+Problem\s+(?P<num>\d{1,2})",
        guess,
        flags=re.IGNORECASE,
    )
    if match:
        comp = re.sub(r"\s+", " ", match.group("comp")).strip().title()
        return f"{comp} {match.group('year')}/{match.group('num')}"
    if re.match(r"^c\d+h\d+", tail):
        return f"AoPS {tail}"
    return ""


# --------------------------------------------------------------------------- #
# the parser
# --------------------------------------------------------------------------- #
def parse_fixture(
    rows: Sequence[dict],
    *,
    puid_map: dict[str, str] | None = None,
    default_category: str = "misc",
    default_track: str = "olympiad",
    skip_missing_statement: bool = False,
    only_puids: set[str] | None = None,
    limit: int | None = None,
    record_warnings: bool = True,
) -> IngestionResult:
    """
    Turn fixture rows into :class:`ParsedProblem` objects.

    The parser is deliberately tolerant: it recognises the documented ARCH models,
    plus a family of legacy/renamed shapes, and reports anything it could not use
    in ``warnings`` rather than failing the whole import.
    """
    puid_map = {k.strip(): v.strip() for k, v in (puid_map or {}).items()}
    warnings: list[str] = []
    by_pk: dict[Any, ParsedProblem] = {}
    hint_rows: list[dict] = []
    solution_rows: list[dict] = []
    stats = {
        "rows_scanned": 0,
        "problem_rows": 0,
        "hint_rows": 0,
        "solution_rows": 0,
        "unknown_models_ignored": 0,
        "problems_built": 0,
        "skipped": 0,
    }

    # ---- pass 1: problems -------------------------------------------------- #
    for row in rows:
        stats["rows_scanned"] += 1
        model = _model_key(row)
        if model in PROBLEM_MODELS:
            stats["problem_rows"] += 1
            fields = _fields(row)
            raw_puid = _first_str(fields, PUID_KEYS)
            hyperlink = _first_str(fields, HYPERLINK_KEYS)
            puid, legacy_puid, note = resolve_puid(raw_puid, hyperlink, puid_map)
            statement = _first_str(fields, STATEMENT_KEYS)
            if note and record_warnings:
                warnings.append(note)
            if not puid:
                stats["skipped"] += 1
                if record_warnings:
                    warnings.append(f"skipped problem pk={row.get('pk')}: no usable PUID")
                continue
            if only_puids and puid not in only_puids and legacy_puid not in only_puids:
                continue
            parsed = ParsedProblem(
                puid=puid,
                legacy_puid=legacy_puid,
                statement_tex=statement,
                hyperlink=hyperlink,
                source_pk=row.get("pk"),
            )
            parsed.warnings = []
            if not statement and record_warnings:
                parsed.warnings.append(
                    f"{puid}: fixture carries no statement text (statements normally live in "
                    "arch/data/<PUID>.tex); add it later via the admin or a supplementary source"
                )
            if not statement and skip_missing_statement:
                stats["skipped"] += 1
                continue
            by_pk[row.get("pk")] = parsed
        elif model in HINT_MODELS:
            hint_rows.append(row)
            stats["hint_rows"] += 1
        elif _is_solution_model(model):
            solution_rows.append(row)
            stats["solution_rows"] += 1
        else:
            stats["unknown_models_ignored"] += 1

    # ---- pass 2: hints ----------------------------------------------------- #
    hint_order: dict[Any, int] = {}
    for row in hint_rows:
        fields = _fields(row)
        problem_pk = _fk_target(fields)
        target = by_pk.get(problem_pk)
        if target is None:
            continue
        text = _first_str(fields, HINT_TEXT_KEYS) or _longest_str(fields, ignore=("keywords",))
        if not text:
            continue
        raw_order = fields.get(HINT_ORDER_KEYS[0])
        try:
            order = int(raw_order)  # ARCH numbers hints (e.g. 25, 35)
        except (TypeError, ValueError):
            order = None
        hint_order[problem_pk] = hint_order.get(problem_pk, 0) + 1
        target.hints.append(
            ParsedHint(
                order_index=order if order and order > 0 else hint_order[problem_pk],
                content_md=text,
                keywords=_first_str(fields, ("keywords", "tags")),
                source_pk=row.get("pk"),
            )
        )

    # ---- pass 3: official solutions ---------------------------------------- #
    for row in solution_rows:
        fields = _fields(row)
        problem_pk = _fk_target(fields)
        target = by_pk.get(problem_pk)
        if target is None:
            continue
        text = _longest_str(fields, ignore=("problem", "problem_id", "problem_pk"))
        if not text:
            continue
        target.official_tex = text
        target.attribution = "ARCH fixture"

    # ---- finalise ---------------------------------------------------------- #
    problems: list[ParsedProblem] = []
    for parsed in by_pk.values():
        # Re-number hints 1..n (ARCH's `number` field is a hint ID, not a tier).
        parsed.hints.sort(key=lambda h: (h.order_index, str(h.source_pk)))
        for index, hint in enumerate(parsed.hints, start=1):
            hint.order_index = index
        hint_keywords = " ".join(h.keywords for h in parsed.hints)
        parsed.category = (
            infer_category(parsed.puid, parsed.statement_tex, hint_keywords)
            if default_category == "auto"
            else default_category
        )
        parsed.difficulty_track = (
            infer_track(parsed.puid, parsed.statement_tex) if default_track == "auto" else default_track
        )
        if record_warnings:
            warnings.extend(parsed.warnings)
        problems.append(parsed)

    problems.sort(key=lambda p: p.puid)
    if limit:
        problems = problems[:limit]
    stats["problems_built"] = len(problems)
    return IngestionResult(
        problems=problems,
        stats=stats,
        warnings=[w for w in dict.fromkeys(warnings) if w],
    )


def iter_parsed(fixture_path: str | Path, **kwargs) -> tuple[IngestionResult, Iterator[ParsedProblem]]:
    """Convenience wrapper: parse a fixture file and iterate the parsed problems."""
    result = parse_fixture(load_fixture(fixture_path), **kwargs)
    return result, iter(result.problems)


# --------------------------------------------------------------------------- #
# database writer (Django ORM; imported lazily so the parser stays standalone)
# --------------------------------------------------------------------------- #
def ingest_into_database(
    result: IngestionResult,
    *,
    dry_run: bool = False,
    update_existing: bool = True,
    keep_legacy_solutions: bool = True,
) -> dict:
    """
    Upsert parsed problems into the database.  Idempotent: re-running the same
    fixture updates rows in place and never duplicates hints.

    Returns a summary dict with created/updated/unchanged counters.
    """
    from django.db import transaction  # local import: keeps this module CLI-usable

    from .models import Hint, Problem, Solution

    summary = {"created": 0, "updated": 0, "unchanged": 0, "hints": 0, "solutions": 0, "skipped": 0}
    for parsed in result.problems:
        existing = Problem.objects.filter(puid=parsed.puid).first()
        if existing is None and parsed.legacy_puid:
            existing = Problem.objects.filter(legacy_puid=parsed.legacy_puid, puid=parsed.legacy_puid).first()

        if existing is not None and not update_existing:
            summary["skipped"] += 1
            continue

        if dry_run:
            summary["created" if existing is None else "updated"] += 1
            summary["hints"] += len(parsed.hints)
            summary["solutions"] += 1 if parsed.official_tex else 0
            continue

        with transaction.atomic():
            if existing is None:
                problem = Problem.objects.create(
                    puid=parsed.puid,
                    legacy_puid=parsed.legacy_puid,
                    statement_tex=parsed.statement_tex or "(statement pending)",
                    category=parsed.category,
                    difficulty_track=parsed.difficulty_track,
                    source_url=parsed.hyperlink if _looks_like_url(parsed.hyperlink) else "",
                )
                summary["created"] += 1
            else:
                problem = existing
                changed_fields = []
                for field_name, value in (
                    ("statement_tex", parsed.statement_tex),
                    ("category", parsed.category),
                    ("difficulty_track", parsed.difficulty_track),
                    ("legacy_puid", parsed.legacy_puid or existing.legacy_puid),
                ):
                    if value and getattr(problem, field_name) != value:
                        setattr(problem, field_name, value)
                        changed_fields.append(field_name)
                if changed_fields:
                    problem.save(update_fields=[*changed_fields, "updated_at"])
                    summary["updated"] += 1
                else:
                    summary["unchanged"] += 1

            for hint in parsed.hints:
                _, created = Hint.objects.update_or_create(
                    problem=problem,
                    order_index=hint.order_index,
                    defaults={"content_md": hint.content_md, "keywords": hint.keywords[:255]},
                )
                summary["hints"] += 1 if created else 0

            if parsed.official_tex:
                existing_solution = Solution.objects.filter(problem=problem).first()
                if existing_solution is None or existing_solution.official_tex != parsed.official_tex:
                    if existing_solution is None or not keep_legacy_solutions:
                        Solution.objects.update_or_create(
                            problem=problem,
                            defaults={
                                "official_tex": parsed.official_tex,
                                "attribution": parsed.attribution or "ARCH fixture",
                            },
                        )
                        summary["solutions"] += 1
    return summary


def _looks_like_url(value: str) -> bool:
    return value.startswith(("http://", "https://"))


def load_puid_map(path: str | Path | None) -> dict[str, str]:
    """Load a JSON ``{"ARCH_CODE": "IMO 2016/4"}`` mapping (optional)."""
    if not path:
        return {}
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("--puid-map must be a JSON object mapping ARCH code -> PUID")
    return {str(k): str(v) for k, v in data.items()}
